# shellcheck shell=bash
# Optional apps. Sourced by the hbox CLI after common.sh.
#
# An app is a folder with compose.yaml and app.json, either shipped with HBOX
# (apps/NAME, arrives with `hbox update`) or your own (local/apps/NAME, never
# touched by git). Enabled apps are listed in HBOX_APPS in .env. For each one
# HBOX:
#   - runs the folder as Compose project hbox-app-NAME (listed in Dockge too),
#   - serves it over HTTPS on its own port through nginx (app.json "port"),
#   - adds it to the dashboard and to backups (DATA_ROOT/apps/NAME).
#
# app.json:
#   {
#     "name": "Status",                       shown on the dashboard
#     "description": "Uptime monitoring",
#     "port": 4443,                           HTTPS port on every address
#     "upstream": "http://uptime-kuma:3001",  container:port on hbox-frontend
#     "health": "/",                          path that answers when up (optional)
#     "max_body": "100M"                      upload limit (optional, default 100M)
#   }
# plus an optional logo.svg or logo.png next to it, shown on the dashboard.

HBOX_NGINX_APPS_DIR=${HBOX_NGINX_APPS_DIR:-$HBOX_STATE/nginx-apps}
HBOX_LOCAL_DIR=$HBOX_HOME/local
# Ports nginx already uses for HBOX itself.
HBOX_RESERVED_PORTS=" 80 443 2443 3443 5443 6443 "

app_dir() {
    local name=$1
    if [ -f "$HBOX_LOCAL_DIR/apps/$name/app.json" ]; then
        printf '%s/apps/%s' "$HBOX_LOCAL_DIR" "$name"
    elif [ -f "$HBOX_HOME/apps/$name/app.json" ]; then
        printf '%s/apps/%s' "$HBOX_HOME" "$name"
    else
        return 1
    fi
}

app_valid_name() {
    [[ $1 =~ ^[a-z0-9][a-z0-9-]{0,30}$ ]]
}

app_get() {
    jq -er --arg key "$2" '.[$key] // empty' "$(app_dir "$1")/app.json"
}

apps_available() {
    local dir
    for dir in "$HBOX_HOME"/apps/*/ "$HBOX_LOCAL_DIR"/apps/*/; do
        [ -f "$dir/app.json" ] && basename "$dir"
    done | sort -u
}

apps_enabled() {
    env_get_default HBOX_APPS '' | tr ',' '\n' | sed '/^$/d'
}

app_is_enabled() {
    apps_enabled | grep -Fxq -- "$1"
}

app_project() {
    printf 'hbox-app-%s' "$1"
}

app_compose() {
    local name=$1 dir
    shift
    dir=$(app_dir "$name") || die "Unknown app: $name"
    docker compose --project-name "$(app_project "$name")" --project-directory "$dir" \
        -f "$dir/compose.yaml" --env-file "$HBOX_ENV_FILE" "$@"
}

# Check app.json before anything is generated from it.
app_validate() {
    local name=$1 dir port upstream body other
    app_valid_name "$name" || die "App names use lowercase letters, digits and '-': $name"
    dir=$(app_dir "$name") || die "Unknown app: $name (see: hbox apps list)"
    [ -f "$dir/compose.yaml" ] || die "$dir has no compose.yaml."
    jq -e . "$dir/app.json" >/dev/null 2>&1 || die "$dir/app.json is not valid JSON."
    port=$(app_get "$name" port) || die "$dir/app.json needs a \"port\"."
    [[ $port =~ ^[0-9]+$ ]] && [ "$port" -ge 1024 ] && [ "$port" -le 65535 ] ||
        die "$name: port must be 1024-65535 (got $port)."
    case $HBOX_RESERVED_PORTS in *" $port "*) die "$name: port $port is used by HBOX itself." ;; esac
    upstream=$(app_get "$name" upstream) || die "$dir/app.json needs an \"upstream\"."
    [[ $upstream =~ ^https?://[A-Za-z0-9._-]+:[0-9]+$ ]] ||
        die "$name: upstream must look like http://container:port (got $upstream)."
    body=$(app_get "$name" max_body || echo 100M)
    [[ $body =~ ^[0-9]+[kKmMgG]?$ ]] || die "$name: max_body must look like 100M (got $body)."
    while IFS= read -r other; do
        [ "$other" = "$name" ] && continue
        app_dir "$other" >/dev/null || continue
        [ "$(app_get "$other" port 2>/dev/null)" = "$port" ] && die "$name and $other both use port $port."
    done < <(apps_enabled)
    return 0
}

# nginx server block (own port) and dashboard health check for one app.
app_render_nginx() {
    local name=$1 port upstream body health var
    port=$(app_get "$name" port)
    upstream=$(app_get "$name" upstream)
    body=$(app_get "$name" max_body || echo 100M)
    health=$(app_get "$name" health || true)
    var=app_${name//-/_}
    cat > "$HBOX_NGINX_APPS_DIR/$name.conf.tmp" <<EOF
# Generated by hbox from $(app_dir "$name")/app.json. Do not edit.
server {
    listen $port ssl;
    server_name _;
    client_max_body_size $body;

    location / {
        include /etc/nginx/conf.d/hbox-proxy.inc;
        proxy_set_header Host \$http_host;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_ssl_verify off;
        set \$$var $upstream;
        proxy_pass \$$var;
    }
}
EOF
    mv -f "$HBOX_NGINX_APPS_DIR/$name.conf.tmp" "$HBOX_NGINX_APPS_DIR/$name.conf"
    if [ -n "$health" ]; then
        [[ $health =~ ^/[A-Za-z0-9._/?=\&-]*$ ]] || die "$name: health must be a path like /api/ping."
        cat > "$HBOX_NGINX_APPS_DIR/$name.health.tmp" <<EOF
# Generated by hbox. Included in the dashboard's server block.
location = /health/$name {
    include /etc/nginx/conf.d/hbox-proxy.inc;
    proxy_set_header Host \$host;
    proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
    proxy_ssl_verify off;
    set \$${var}_health $upstream;
    rewrite ^ $health break;
    proxy_pass \$${var}_health;
}
EOF
        mv -f "$HBOX_NGINX_APPS_DIR/$name.health.tmp" "$HBOX_NGINX_APPS_DIR/$name.health"
    else
        rm -f "$HBOX_NGINX_APPS_DIR/$name.health"
    fi
}

# hbox-core's compose.override.yaml: publish every enabled app's port.
apps_render_ports() {
    local override=$HBOX_HOME/stacks/hbox-core/compose.override.yaml name ports=()
    while IFS= read -r name; do
        app_dir "$name" >/dev/null || continue
        ports+=("$(app_get "$name" port)")
    done < <(apps_enabled)
    if [ "${#ports[@]}" -eq 0 ]; then
        rm -f "$override"
        return 0
    fi
    {
        echo "# Generated by hbox for the enabled optional apps. Do not edit."
        echo "services:"
        echo "  hbox-nginx:"
        echo "    ports:"
        for name in "${ports[@]}"; do printf '      - "%s:%s"\n' "$name" "$name"; done
    } > "$override.tmp"
    mv -f "$override.tmp" "$override"
}

# The dashboard's app list: local/dashboard.json (your own copy) or the
# shipped config/dashboard/apps.json, plus a card per enabled app.
apps_render_dashboard() {
    local base=$HBOX_HOME/config/dashboard/apps.json extra='[]' name dir out logo ext
    [ -f "$HBOX_LOCAL_DIR/dashboard.json" ] && base=$HBOX_LOCAL_DIR/dashboard.json
    install -d -m 755 "$HBOX_STATUS_DIR" "$HBOX_STATUS_DIR/icons"
    rm -f "$HBOX_STATUS_DIR"/icons/app-*
    while IFS= read -r name; do
        dir=$(app_dir "$name") || continue
        logo=''
        for ext in svg png; do
            if [ -f "$dir/logo.$ext" ] && [ ! -L "$dir/logo.$ext" ]; then
                install -m 644 "$dir/logo.$ext" "$HBOX_STATUS_DIR/icons/app-$name.$ext"
                logo=/app-icons/app-$name.$ext
                break
            fi
        done
        extra=$(jq -c --arg id "$name" --arg logo "$logo" --argjson list "$extra" \
            '$list + [{name: (.name // $id), description: (.description // ""),
                       icon: (.icon // "app"), port: .port}
                      + (if $logo != "" then {logo: $logo} else {} end)
                      + (if .health then {health: $id} else {} end)]' "$dir/app.json") || continue
    done < <(apps_enabled)
    local backups=false
    if declare -F backrest_enabled >/dev/null && backrest_enabled; then
        backups=true
    fi
    out=$(mktemp "$HBOX_STATUS_DIR/apps.json.XXXXXX")
    # The Backups card appears once backups are set up (Backrest runs).
    if ! jq --argjson extra "$extra" --argjson backups "$backups" '
            (if $backups then . else .sections |= map(.items |= map(select(.health != "backups"))) end)
            | if ($extra | length) == 0 then .
            elif any(.sections[]; .name == "Apps")
            then .sections |= map(if .name == "Apps" then .items += $extra else . end)
            else .sections = [{name: "Apps", items: $extra}] + .sections end' "$base" > "$out"; then
        rm -f "$out"
        warn "$base is not valid JSON; the dashboard keeps its previous app list."
        return 0
    fi
    chmod 644 "$out"
    mv -f "$out" "$HBOX_STATUS_DIR/apps.json"
}

# Regenerate everything derived from the enabled apps.
apps_render_all() {
    local name file
    install -d -m 755 "$HBOX_NGINX_APPS_DIR"
    # Drop files of apps that are no longer enabled (or no longer exist).
    for file in "$HBOX_NGINX_APPS_DIR"/*.conf "$HBOX_NGINX_APPS_DIR"/*.health; do
        [ -e "$file" ] || continue
        name=$(basename "${file%.*}")
        if ! app_is_enabled "$name" || ! app_dir "$name" >/dev/null; then
            rm -f -- "$file"
        fi
    done
    while IFS= read -r name; do
        if ! app_dir "$name" >/dev/null; then
            warn "Enabled app '$name' no longer exists; skipping it (sudo hbox apps disable $name)."
            continue
        fi
        app_validate "$name"
        app_render_nginx "$name"
        app_link_dockge "$name"
    done < <(apps_enabled)
    apps_render_ports
    apps_render_dashboard
}

# Dockge lists stacks found in HBOX_HOME/stacks; link the app folder there.
app_link_dockge() {
    local name=$1 dir link
    dir=$(app_dir "$name")
    link=$HBOX_HOME/stacks/$(app_project "$name")
    ln -sfn "$dir" "$link"
    ln -sfn "$HBOX_ENV_FILE" "$dir/.env"
}

apps_start_enabled() {
    local name data
    data=$(env_get_default DATA_ROOT /DATA)
    while IFS= read -r name; do
        app_dir "$name" >/dev/null || continue
        install -d -m 750 "$data/apps/$name"
        log "Starting app $name"
        with_retries "Starting app $name" app_compose "$name" up -d --remove-orphans --wait --wait-timeout 300
    done < <(apps_enabled)
}

nginx_reload() {
    container_running hbox-nginx || return 0
    if ! docker exec hbox-nginx nginx -t >/dev/null 2>&1; then
        docker exec hbox-nginx nginx -t >&2 || true
        die "The nginx configuration is invalid (above); nginx keeps running the previous one."
    fi
    docker exec hbox-nginx nginx -s reload >/dev/null
}

cmd_apps() {
    local sub=${1:-list} name list
    [ "$#" -gt 0 ] && shift
    case $sub in
        list)
            printf '%-20s %-9s %-6s %s\n' APP STATE PORT DESCRIPTION
            while IFS= read -r name; do
                printf '%-20s %-9s %-6s %s\n' "$name" \
                    "$(app_is_enabled "$name" && echo enabled || echo -)" \
                    "$(app_get "$name" port 2>/dev/null || echo ?)" \
                    "$(app_get "$name" description 2>/dev/null || true)"
            done < <(apps_available)
            ;;
        enable)
            require_root; require_docker; require_env
            name=${1:-}; [ -n "$name" ] || die "Usage: hbox apps enable NAME"
            app_is_enabled "$name" && { log "$name is already enabled."; return 0; }
            app_validate "$name"
            list=$( (apps_enabled; echo "$name") | paste -sd, -)
            env_set HBOX_APPS "$list"
            if ! apps_apply; then
                env_set HBOX_APPS "$( apps_enabled | grep -Fxv -- "$name" | paste -sd, -)"
                die "Could not enable $name."
            fi
            log "$name is running: https://$(primary_ip || echo hbox.local):$(app_get "$name" port)/"
            ;;
        disable)
            require_root; require_docker; require_env
            name=${1:-}; [ -n "$name" ] || die "Usage: hbox apps disable NAME"
            app_is_enabled "$name" || { log "$name is not enabled."; return 0; }
            app_dir "$name" >/dev/null && app_compose "$name" down || true
            env_set HBOX_APPS "$(apps_enabled | grep -Fxv -- "$name" | paste -sd, -)"
            rm -f "$HBOX_HOME/stacks/$(app_project "$name")"
            apps_apply
            log "$name is stopped and removed from the dashboard. Its data in $(env_get_default DATA_ROOT /DATA)/apps/$name is kept."
            ;;
        *) die "Usage: hbox apps list | enable NAME | disable NAME" ;;
    esac
}

# Bring nginx and the apps in line with HBOX_APPS.
apps_apply() {
    apps_render_all
    stack_up hbox-core
    apps_start_enabled
    nginx_reload
}
